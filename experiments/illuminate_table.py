#!/usr/bin/env python3
"""The tables behind the model's wall-mounted lamps, from OSLUV's Illuminate (its engine, guv_calcs).

For rooms of each floor area and ceiling height, with Aerolamps at 1, 2, 3 and 4 times the page's density (one per
250 sq ft, at least one), mounted high on the walls, 10 cm below the ceiling, and aimed one of two ways:
  wall    angled down (Illuminate's "edge" placement, its default for the Aerolamp: aimed at the foot of the opposite wall)
  across  pointed straight across the room (Illuminate's "horizontal" placement: aimed level, at the opposite wall)
Each table holds, for every density, floor area and ceiling height:
  path   the light's average path through the room's air, in metres per lamp
         (whole-room average fluence x volume / total lamp output, both from Illuminate)
  limit  the multiple of full output at which Illuminate's exposure check is exactly met for 8 hours a day
         (ANSI/IES RP-27.1-22, ACGIH limits). Below 1 the lamps must be dimmed to that share; stored up to 4.
         Found by running the check with its dose time set to 800 hours, so that it always asks for dimming, and
         multiplying the answer by 100: the dose is the irradiance times the time.
python3 experiments/illuminate_table.py [wall|across] [--install]
Writes src/illuminate-<name>.json; --install pastes it into src/params.js.   pip install guv-calcs
"""
import json, math, os, re, sys, warnings
import numpy as np
import guv_calcs
from guv_calcs import Room, Lamp
warnings.filterwarnings('ignore')
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
AREAS = [9, 12, 14, 17, 20, 24, 25, 30, 35, 42, 50, 60, 70, 80, 100, 110, 134, 140, 170, 200]   # includes the floor areas of the default building's rooms, so those are read exactly
HEIGHTS = [2.15, 2.3, 2.4, 2.45, 2.6, 2.7, 3.0, 3.5]
NAME = 'across' if 'across' in sys.argv else 'wall'
MODE, ASPECT, M2_PER_LAMP = {'wall': 'edge', 'across': 'horizontal'}[NAME], 1.3, 23.2258
MULTS = [1, 2, 3, 4]
def cell(area, h, mult):
    x = math.sqrt(area * ASPECT); y = area / x; n = max(1, round(area / M2_PER_LAMP)) * mult
    room = Room(x=x, y=y, z=h)
    for _ in range(n): room.place_lamp(Lamp.from_keyword('aerolamp'), mode=MODE)
    room.add_standard_zones(); room.calculate()
    e = float(np.asarray(room.zone('WholeRoomFluence').get_values()).mean())          # microwatts per cm2
    p = sum(l.get_total_power() for l in room.lamps.values())                          # milliwatts
    c = room.check_lamps(); dims = [d for d in (c.skin_dimming_for_compliance, c.eye_dimming_for_compliance) if d is not None]
    share8 = min(1.0, min(dims)) if dims else 1.0                                      # what the check asks for at its own 8 hours
    for z in ('EyeLimits', 'SkinLimits'): room.zone(z).set_dose_time(hours=800)
    c = room.check_lamps(); limit = 100 * min(c.skin_dimming_for_compliance, c.eye_dimming_for_compliance)
    assert abs(min(1.0, limit) - share8) < 2e-3, (area, h, mult, limit, share8)
    return e * area * h / (0.1 * p), limit, p / n
path, limit, pw = [], [], 0
for m in MULTS:
    pm, lm = [], []
    for a in AREAS:
        pr, lr = [], []
        for h in HEIGHTS:
            L, s, pw = cell(a, h, m); pr.append(round(float(L), 2)); lr.append(round(min(4.0, float(s)), 3))
        pm.append(pr); lm.append(lr); print(m, a, pr, lr, flush=True)
    path.append(pm); limit.append(lm)
out = {'source': f'OSLUV Illuminate (guv_calcs {guv_calcs.__version__}), Aerolamp, "{MODE}" placement, aspect {ASPECT}, 1 to 4 times one lamp per 250 sq ft',
       'lampMw': round(pw, 1), 'm2PerLamp': M2_PER_LAMP, 'mults': MULTS, 'areas': AREAS, 'heights': HEIGHTS, 'path': path, 'limit': limit}
json.dump(out, open(os.path.join(ROOT, 'src', f'illuminate-{NAME}.json'), 'w'))
if '--install' in sys.argv:
    p = os.path.join(ROOT, 'src', 'params.js'); s = open(p).read()
    tag = f'illuminate-{NAME}'
    block = f'// <{tag}> generated by experiments/illuminate_table.py; do not edit by hand\nexport const ILLUMINATE_{NAME.upper()} = ' + json.dumps(out) + f';\n// </{tag}>'
    s = re.sub(rf'// <{tag}>.*?// </{tag}>', lambda m: block, s, flags=re.S) if f'// <{tag}>' in s else s + '\n' + block + '\n'
    open(p, 'w').write(s); print('installed in src/params.js')
