import { chromium, CHROME, PAGE } from './lib.mjs';
const b = await chromium.launch({ ...CHROME, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1440, height: 950 } });
p.on('pageerror', (e) => console.log('PAGEERR', String(e.stack || e).slice(0, 500)));
await p.goto(PAGE);
await p.waitForFunction(() => window.__film && window.__film.ready(), null, { timeout: 60000 });
await p.screenshot({ path: 'shots/v3-film.png', fullPage: true });
await p.click('#tab-model');
await p.waitForFunction(() => /seasons simulated/.test(document.querySelector('#runstat').textContent), null, { timeout: 150000 });
const before = await p.textContent('#sentence');
const row = p.locator('.prow', { hasText: 'Virus breathed out by a typical infected person at rest' });
console.log('emission row:', (await row.textContent()).slice(0, 420));
await row.locator('input[type=range]').evaluate((e) => { e.value = e.max; e.dispatchEvent(new Event('input', { bubbles: true })); });
await p.waitForTimeout(3000);
await p.waitForFunction(() => /seasons simulated/.test(document.querySelector('#runstat').textContent), null, { timeout: 200000 });
console.log('default  :', before.slice(0, 200)); console.log('emission at top of range:', (await p.textContent('#sentence')).slice(0, 200));
await p.setViewportSize({ width: 400, height: 800 }); await p.click('#tab-film'); await p.waitForTimeout(300); console.log('phone scrollW', await p.evaluate(() => document.documentElement.scrollWidth));
await p.screenshot({ path: 'shots/v3-phone.png' });
await b.close();
